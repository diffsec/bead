const (
	rcBegin = "# >>> bead >>>"
	rcEnd   = "# <<< bead <<<"
)

// shellSnippet defines a claude function that routes Claude Code through
// the proxy when the proxy answers its health check, and runs Claude Code
// directly otherwise.
func shellSnippet(proxyURL string) string {
	return `# Generated by bead setup. Routes Claude Code through the bead memory proxy.
# Remove the bead block from your shell rc file to turn it off.
BEAD_PROXY_URL="` + proxyURL + `"
claude() {
  if curl -fsS -m 1 "$BEAD_PROXY_URL/bead/health" >/dev/null 2>&1; then
    ANTHROPIC_BASE_URL="$BEAD_PROXY_URL" CLAUDE_CODE_GATEWAY_HINT_HEADERS=1 command claude "$@"
  else
    echo "bead: the proxy at $BEAD_PROXY_URL is not running; Claude Code starts without memory." >&2
    command claude "$@"
  fi
}
`
}

// rcFile picks the rc file for the login shell.
func rcFile(homeDir, shell string) (string, error) {
	switch filepath.Base(shell) {
	case "zsh":
		return filepath.Join(homeDir, ".zshrc"), nil
	case "bash":
		return filepath.Join(homeDir, ".bashrc"), nil
	}
	return "", fmt.Errorf("setup: shell %q is not supported; source the snippet by hand", shell)
}

// addRCBlock adds or replaces the marked bead block in the rc file.
func addRCBlock(rc, snippetPath string) (bool, error) {
	data, err := os.ReadFile(rc)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	block := rcBegin + "\n[ -f \"" + snippetPath + "\" ] && . \"" + snippetPath + "\"\n" + rcEnd + "\n"
	text := string(data)
	if i := strings.Index(text, rcBegin); i >= 0 {
		j := strings.Index(text[i:], rcEnd)
		if j < 0 {
			return false, fmt.Errorf("setup: %s has %q without %q; fix it by hand", rc, rcBegin, rcEnd)
		}
		end := i + j + len(rcEnd)
		if end < len(text) && text[end] == '\n' {
			end++
		}
		if text[i:end] == block {
			return false, nil
		}
		text = text[:i] + block + text[end:]
	} else {
		if text != "" && !strings.HasSuffix(text, "\n") {
			text += "\n"
		}
		text += "\n" + block
	}
	info, statErr := os.Stat(rc)
	if err := fsutil.WriteAtomic(rc, []byte(text)); err != nil {
		return false, err
	}
	if statErr == nil {
		// Keep the permissions the file had.
		return true, os.Chmod(rc, info.Mode().Perm())
	}
	return true, nil
}

// defaultConfig is the config.yaml that setup writes when none exists. It
// is valid as written: the dream job reports the missing model when it
// runs, and the proxy does not need a model.
const defaultConfig = `# bead configuration. DESIGN.md, "Nightly dream job", describes every field.
dream:
  # The model for the nightly dream job: ollama, anthropic or openai.
  # openai means any OpenAI-compatible endpoint; set base_url to its /v1 root.
  provider: ollama

  # Required for ollama and openai. For Ollama, pull a chat model first:
  #   ollama pull qwen3:8b
  model: ""

  # base_url: http://127.0.0.1:11434

  # For a hosted provider, give the key through one of these. launchd does
  # not pass shell variables, so the nightly run needs api_key_command.
  # Never put the key itself in this file.
  # api_key_env: OPENAI_API_KEY
  # api_key_command: security find-generic-password -s bead-openai -w

  decay_days: 60         # unused facts become dormant after this many days
  max_chunk_chars: 24000 # transcript characters per model call
  hour: 3                # local hour for the nightly run
`

// writeDefaultConfig writes config.yaml if it does not exist. It reports
// whether it wrote the file. It never changes an existing file.
func writeDefaultConfig(home string) (string, bool, error) {
	path := filepath.Join(home, "config.yaml")
	if _, err := os.Stat(path); err == nil {
		return path, false, nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return path, false, err
	}
	if err := os.MkdirAll(home, 0o700); err != nil {
		return path, false, err
	}
	return path, true, fsutil.WriteAtomic(path, []byte(defaultConfig))
}

func cmdSetup(ctx context.Context, args []string, stdin io.Reader, out *printer) (err error) {
	fs := flag.NewFlagSet("setup", flag.ContinueOnError)
	listen := fs.String("listen", "127.0.0.1:7077", "proxy listen address")
	noRC := fs.Bool("no-rc", false, "write the shell snippet but do not change the shell rc file")
	noLoad := fs.Bool("no-load", false, "write the launchd agents but do not load them")
	noDream := fs.Bool("no-dream", false, "do not schedule the nightly dream job")
	noVault := fs.Bool("no-vault", false, "do not offer to create the vault")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if runtime.GOOS != "darwin" {
		return errNotDarwin
	}
	if err := requireLoopback(*listen); err != nil {
		return err
	}
	h, err := home()
	if err != nil {
		return err
	}
	homeDir, err := os.UserHomeDir()
	if err != nil {
		return err
	}

	// 1. The configuration file, and the vault.
	cfgPath, wrote, err := writeDefaultConfig(h)
	if err != nil {
		return err
	}
	if wrote {
		out.f("Wrote %s. Set dream.model in it before the first nightly run.\n", cfgPath)
	} else {
		out.f("Kept the existing %s.\n", cfgPath)
	}
	m, err := open(ctx)
	if err != nil {
		return err
	}
	vaultErr := setupVault(m, *noVault, stdin, out)
	if err := errors.Join(vaultErr, m.Close()); err != nil {
		return err
	}

	// 2. The proxy agent, and the dream agent.
	if err := cmdProxyInstall([]string{"--listen", *listen}, out); err != nil {
		return err
	}
	labels := []string{"com.bead.proxy"}
	if !*noDream {
		if err := cmdDreamInstall(ctx, nil, out); err != nil {
			return err
		}
		labels = append(labels, "com.bead.dream")
	}
	if !*noLoad {
		for _, label := range labels {
			if err := loadAgent(ctx, homeDir, label); err != nil {
				return err
			}
			out.f("Loaded %s.\n", label)
		}
	}

	// 3. The shell snippet and the rc block.
	snippet := filepath.Join(h, "shell.sh")
	if err := fsutil.WriteAtomic(snippet, []byte(shellSnippet("http://"+*listen))); err != nil {
		return err
	}
	out.f("Wrote %s.\n", snippet)
	if *noRC {
		out.f("Add this line to your shell rc file:\n  . %s\n", snippet)
		return nil
	}
	rc, err := rcFile(homeDir, os.Getenv("SHELL"))
	if err != nil {
		return err
	}
	changed, err := addRCBlock(rc, snippet)
	if err != nil {
		return err
	}
	if changed {
		out.f("Added the bead block to %s. Open a new terminal, or run: . %s\n", rc, rc)
	} else {
		out.f("%s already loads the snippet.\n", rc)
	}
	return nil
}

// loadAgent replaces a running agent with the plist on disk.
func loadAgent(ctx context.Context, homeDir, label string) error {
	domain := fmt.Sprintf("gui/%d", os.Getuid())
	plist := filepath.Join(homeDir, "Library", "LaunchAgents", label+".plist")
	// bootout fails when the agent is not loaded; that is the normal first run.
	_ = exec.CommandContext(ctx, "launchctl", "bootout", domain+"/"+label).Run()
	if out, err := exec.CommandContext(ctx, "launchctl", "bootstrap", domain, plist).CombinedOutput(); err != nil {
		return fmt.Errorf("launchctl bootstrap %s: %v: %s", label, err, strings.TrimSpace(string(out)))
	}
	return nil
}

// setupVault offers to create the vault when it does not exist and a
// person is at the terminal. A script gets a hint instead of a prompt.
func setupVault(m *memory.Memory, skip bool, stdin io.Reader, out *printer) error {
	if m.Vault.Initialized() {
		out.ln("The vault exists.")
		return nil
	}
	if skip {
		return nil
	}
	if !term.IsTerminal(int(os.Stdin.Fd())) {
		out.ln("The vault does not exist. Run `bead vault init` to create it for sealed facts.")
		return nil
	}
	if !confirm(stdin, out, "Create the vault for sealed facts now? You choose a passphrase that cannot be recovered.") {
		out.ln("Skipped the vault. Run `bead vault init` later.")
		return nil
	}
	return initVault(m.Vault, stdin, out)
}
